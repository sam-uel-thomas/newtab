#!/usr/bin/env python3
"""Copy the page, Firefox files and installers into builder/templates.js.

The builder works from file:// as well as GitHub Pages, where it can't fetch
sibling files, so it reads them from this script-generated file instead.
Run it after changing index.html, anything in firefox/, or the installers:

    python3 builder/bundle.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = [
    "index.html",
    "firefox/userChrome.css",
    "firefox/user.js",
    "firefox/autoconfig.js",
    "firefox/autoconfig.cfg",
    "install.sh",
    "install.ps1",
]

templates = {name: (ROOT / name).read_text(encoding="utf-8") for name in FILES}
out = ROOT / "builder" / "templates.js"
out.write_text(
    "// Generated by builder/bundle.py from the files at the repo root. Don't edit by hand.\n"
    "window.NEWTAB_TEMPLATES = " + json.dumps(templates, ensure_ascii=False, indent=1) + ";\n",
    encoding="utf-8",
)
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
